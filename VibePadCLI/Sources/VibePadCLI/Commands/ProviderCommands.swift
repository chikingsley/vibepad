import ArgumentParser
import Foundation

#if canImport(FoundationNetworking)
  import FoundationNetworking
#endif

struct Providers: AsyncParsableCommand {
  static let configuration = CommandConfiguration(
    abstract: "Synchronize and verify bundled provider marks.",
    subcommands: [ProvidersSync.self, ProvidersCheck.self]
  )
}

struct ProvidersCheck: ParsableCommand {
  static let configuration = CommandConfiguration(commandName: "check")

  func run() throws {
    let repository = try Repository.locate()
    let metadata = try JSONDecoder().decode(
      ProviderMetadata.self,
      from: Data(contentsOf: repository.url("docs/parity/models-dev-provider-icons.json"))
    )
    guard metadata.schemaVersion == 1, metadata.providerCount == metadata.providers.count,
      Set(metadata.providers).count == metadata.providers.count
    else {
      throw CLIError.message("Invalid provider icon metadata.")
    }

    let assets = repository.url("VibePad/Assets.xcassets")
    let catalog = try String(
      contentsOf: repository.url("VibePad/Features/Components/ProviderIconCatalog.swift"),
      encoding: .utf8
    )
    for provider in metadata.providers {
      let imageSet = assets.appending(path: "Provider-\(provider).imageset")
      guard FileManager.default.fileExists(atPath: imageSet.appending(path: "\(provider).svg").path),
        FileManager.default.fileExists(atPath: imageSet.appending(path: "Contents.json").path),
        catalog.contains("\"\(provider)\"")
      else {
        throw CLIError.message("Provider snapshot is missing: \(provider)")
      }
    }
    print("Provider icon snapshot is complete: \(metadata.providerCount) native SVG assets.")
  }
}

struct ProvidersSync: AsyncParsableCommand {
  static let configuration = CommandConfiguration(commandName: "sync")

  @Option(help: "models.dev-compatible service root.")
  var source = "https://models.dev"

  func run() async throws {
    guard let sourceURL = URL(string: source) else {
      throw CLIError.message("Invalid provider source URL: \(source)")
    }
    let repository = try Repository.locate()
    let apiURL = sourceURL.appending(path: "api.json")
    let (apiData, apiResponse) = try await URLSession.shared.data(from: apiURL)
    try validate(response: apiResponse, for: apiURL)
    guard let providersObject = try JSONSerialization.jsonObject(with: apiData) as? [String: Any],
      !providersObject.isEmpty
    else {
      throw CLIError.message("Provider API did not return an object.")
    }

    let providers = providersObject.keys.sorted()
    let allowed = /^[a-z0-9][a-z0-9.-]*$/
    guard providers.allSatisfy({ $0.wholeMatch(of: allowed) != nil }) else {
      throw CLIError.message("Provider API returned an unsafe identifier.")
    }

    let fileManager = FileManager.default
    let staging = fileManager.temporaryDirectory.appending(path: "vibepad-providers-\(UUID().uuidString)")
    try fileManager.createDirectory(at: staging, withIntermediateDirectories: true)
    defer { try? fileManager.removeItem(at: staging) }

    for provider in providers {
      let logoURL = sourceURL.appending(path: "logos/\(provider).svg")
      let (data, response) = try await URLSession.shared.data(from: logoURL)
      try validate(response: response, for: logoURL)
      guard var svg = String(data: data, encoding: .utf8), svg.hasPrefix("<svg") else {
        throw CLIError.message("Provider mark is not SVG: \(provider)")
      }
      svg = svg.replacingOccurrences(of: "currentColor", with: "#000000")
      let imageSet = staging.appending(path: "Provider-\(provider).imageset")
      try fileManager.createDirectory(at: imageSet, withIntermediateDirectories: true)
      try Data(svg.utf8).write(to: imageSet.appending(path: "\(provider).svg"), options: .atomic)
      let contents: [String: Any] = [
        "images": [["filename": "\(provider).svg", "idiom": "universal"]],
        "info": ["author": "xcode", "version": 1],
        "properties": [
          "preserves-vector-representation": true,
          "template-rendering-intent": "template",
        ],
      ]
      try JSONSerialization.data(withJSONObject: contents, options: [.prettyPrinted, .sortedKeys])
        .write(to: imageSet.appending(path: "Contents.json"), options: .atomic)
    }

    let assets = repository.url("VibePad/Assets.xcassets")
    let existing = try fileManager.contentsOfDirectory(at: assets, includingPropertiesForKeys: nil)
      .filter { $0.lastPathComponent.hasPrefix("Provider-") && $0.pathExtension == "imageset" }
    for imageSet in existing {
      try fileManager.removeItem(at: imageSet)
    }
    for imageSet in try fileManager.contentsOfDirectory(at: staging, includingPropertiesForKeys: nil) {
      try fileManager.copyItem(at: imageSet, to: assets.appending(path: imageSet.lastPathComponent))
    }

    let catalogLines = providers.map { "    \"\($0)\"," }.joined(separator: "\n")
    let catalog = """
      // Generated by `vibepad providers sync`. Do not edit by hand.
      import Foundation

      enum ProviderIconCatalog {
        static let providerIDs: Set<String> = [
      \(catalogLines)
        ]
      }
      """
    try Data(catalog.utf8).write(
      to: repository.url("VibePad/Features/Components/ProviderIconCatalog.swift"), options: .atomic)

    let metadata = ProviderMetadata(
      schemaVersion: 1, source: source, providerCount: providers.count, providers: providers)
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
    try encoder.encode(metadata).write(
      to: repository.url("docs/parity/models-dev-provider-icons.json"), options: .atomic)
    print("Synced \(providers.count) provider icons from \(source).")
  }

  private func validate(response: URLResponse, for url: URL) throws {
    guard let http = response as? HTTPURLResponse, (200..<300).contains(http.statusCode) else {
      throw CLIError.message("Provider request failed: \(url.absoluteString)")
    }
  }
}

private struct ProviderMetadata: Codable {
  let schemaVersion: Int
  let source: String
  let providerCount: Int
  let providers: [String]

  enum CodingKeys: String, CodingKey {
    case schemaVersion = "schema_version"
    case source, providers
    case providerCount = "provider_count"
  }
}
